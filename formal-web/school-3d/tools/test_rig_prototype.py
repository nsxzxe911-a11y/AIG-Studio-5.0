"""Deterministic integration gate for the unapproved skinned model technical fixture."""
import unittest,tempfile,os
from pathlib import Path
from build_rig_prototype import make_model
from verify_prototype import verify

class Prototype(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.source=Path(os.environ.get('AIG_PBR_SOURCE','artifacts/school-3d-prototype-pbr'))
        if not cls.source.exists():
            raise RuntimeError('Texture maps must be generated by skin_materials.py first')
    def test_valid_glb_structural_animation(self):
        with tempfile.TemporaryDirectory() as d:
            path=Path(d)/'candidate.glb'
            report=make_model(self.source,path)
            audit=verify(path)
            self.assertTrue(audit['valid_glTF2_technical'],audit['errors'])
            self.assertEqual(report['joints'],33)
            self.assertEqual(report['textures'],9)
            self.assertGreater(report['triangles'],30000)
            self.assertEqual(len(report['clips']),2)
            self.assertEqual(report['visualAuthority'],'NOT_APPROVED')
            self.assertIn('NOT APPROVED',audit['appearance_approval'])
    def test_reproducible_glb_hash(self):
        with tempfile.TemporaryDirectory() as d:
            a=make_model(self.source,Path(d)/'a.glb')
            b=make_model(self.source,Path(d)/'b.glb')
            self.assertEqual(a['sha256'],b['sha256'])

if __name__=='__main__':unittest.main()