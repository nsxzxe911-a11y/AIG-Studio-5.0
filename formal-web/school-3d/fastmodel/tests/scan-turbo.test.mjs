import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {SCAN_SPEED_MODES,scanSpeedPolicy,createTurboScanController} from '../web/scan-turbo.mjs';
import {buildScanOverlay} from '../web/scan-overlay.mjs';
test('turbo moves from immediate true bones to optional outlines then sampled depth, no fake 60 FPS',()=>{
 assert.deepEqual([...SCAN_SPEED_MODES],['turbo','balanced','precise']);
 const ctl=createTurboScanController({speed:'turbo',small:false});
 const out=[];
 for(let i=0;i<12;i++)out.push(ctl.sample({mainSubmitMs:4,overlayMs:2,topologyReady:i>=1}));
 assert.equal(out[0].phase,'bones');
 assert.equal(out[2].phase,'bones');
 assert.equal(out[3].phase,'outline');
 assert.equal(out[9].phase,'depth');
 assert.equal(out[9].depthMode,'sampled');
 assert.equal(out[0].renderMode,'bones');
 assert.ok(out.every(x=>x.actualHardwareFpsMeasured===false&&x.sourceVerticesUnchanged===true));
});
test('mobile prioritizes skin-safe bones and eco profile, never enabling CPU depth in turbo',()=>{
 const ctl=createTurboScanController({speed:'turbo',small:true});
 const samples=Array.from({length:20},()=>ctl.sample({mainSubmitMs:3,overlayMs:1,topologyReady:true}));
 assert.equal(scanSpeedPolicy('turbo',true).density,'eco');
 assert.ok(samples.every(x=>x.density==='eco'&&x.depthMode==='off'&&x.intervalMs>=120));
 assert.equal(samples[0].phase,'bones');
 assert.equal(samples.at(-1).phase,'outline');
 assert.equal(samples.at(-1).renderMode,'bones-outline');
});
test('two hot measurements degrade to real bone-only; after cool frames contours recover',()=>{
 const ctl=createTurboScanController({speed:'balanced'});
 for(let i=0;i<8;i++)ctl.sample({mainSubmitMs:4,overlayMs:3,topologyReady:true});
 assert.equal(ctl.sample({mainSubmitMs:40,overlayMs:4,topologyReady:true}).throttled,false);
 const hot=ctl.sample({mainSubmitMs:43,overlayMs:17,topologyReady:true});
 assert.equal(hot.phase,'bones');
 assert.equal(hot.depthMode,'off');
 assert.equal(hot.throttled,true);
 let cold;
 for(let i=0;i<9;i++)cold=ctl.sample({mainSubmitMs:4,overlayMs:2,topologyReady:true});
 assert.equal(cold.throttled,false);
 const restored=ctl.sample({mainSubmitMs:4,overlayMs:2,topologyReady:true});
 assert.ok(['outline','depth'].includes(restored.phase));
 ctl.reset('turbo',true);
 assert.equal(ctl.sample({topologyReady:false}).phase,'bones');
});
test('speed controller validates modes and budgets, never synthesizes bones or changes mesh',()=>{
 assert.throws(()=>scanSpeedPolicy('unlimited'),/SCAN_SPEED_INVALID/);
 const ctl=createTurboScanController();
 assert.throws(()=>ctl.sample({mainSubmitMs:-1}),/SCAN_SPEED_TELEMETRY_INVALID/);
 assert.throws(()=>ctl.sample({requestedDensity:'infinite'}),/SCAN_SPEED_OPTIONS_INVALID/);
 assert.throws(()=>ctl.sample({requestedMode:'simulated'}),/SCAN_SPEED_MODE_INVALID/);
 const file={g:{nodes:[{children:[1]},{}],skins:[{joints:[0,1]}],meshes:[]}};
 let reads=0,reader=()=>{reads++;return new Float32Array(16);};
 const a=buildScanOverlay(file,reader,{density:'eco',geometry:'bones'});
 assert.equal(a.status,'SOURCE_READY');
 assert.equal(a.bones.length,1);
 assert.equal(a.surfaces.length,0);
 assert.equal(a.triangles,0);
 assert.equal(reads,0);
 const src=JSON.stringify(file.g);
 assert.equal(JSON.stringify(file.g),src);
 assert.throws(()=>buildScanOverlay(file,reader,{geometry:'fiction'}),/SCAN_GEOMETRY_MODE_INVALID/);
});
