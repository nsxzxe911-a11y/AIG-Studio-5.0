/**
 * V95 browser-local image-to-landmark proposal.
 * A real, deterministic pixel algorithm; not a pretrained face detector.
 * If a vetted local ONNX/WASM landmark model is later supplied, use its
 * labeled observations. Fallback must ALWAYS report LOW confidence.
 */
export const AIG_REAL3D_V95_VISION_SCHEMA='AIG_REAL3D_V95_LOCAL_IMAGE_LANDMARK_PROPOSAL_V1';
const fail=x=>{throw Error('REAL3D_V95_VISION_'+x);};
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
const hex=x=>typeof x==='string'&&/^[a-f0-9]{64}$/i.test(x);
export function analyzeAIGReal3DPortraitPixels({
 rgba,width,height,imageSha256,faceLandmarks=null
}={}){
 if(!hex(imageSha256)||!Number.isInteger(width)||!Number.isInteger(height)||
  width<96||height<96||width>4096||height>4096||
  !rgba||rgba.length!==4*width*height||
  width*height>8_000_000)fail('SOURCE_IMAGE_OR_SHA_INVALID');
 // Pixels may include hair, light, costumes, and image backgrounds.
 // Estimate skin-color envelope only; never call it identity recognition.
 const stride=Math.max(1,Math.floor(Math.sqrt(width*height/110000)));
 let count=0,xsum=0,ysum=0,minX=width,minY=height,maxX=0,maxY=0;
 for(let y=0;y<Math.floor(height*.70);y+=stride)
  for(let x=Math.floor(width*.1);x<Math.floor(width*.9);x+=stride){
   const k=(y*width+x)*4,[r,g,b,a]=rgba.slice(k,k+4);
   if(a<200)continue;
   const max=Math.max(r,g,b),min=Math.min(r,g,b);
   const likely=(r>75&&g>36&&b>24&&r>g*1.08&&r>b*1.12&&max-min>19);
   if(!likely)continue;
   count++;xsum+=x;ysum+=y;minX=Math.min(minX,x);
   minY=Math.min(minY,y);maxX=Math.max(maxX,x);maxY=Math.max(maxY,y);
  }
 const supplied=faceLandmarks!==null;
 if(supplied&&(typeof faceLandmarks!=='object'||
  ![faceLandmarks.faceBox?.x,faceLandmarks.faceBox?.y,
   faceLandmarks.faceBox?.width,faceLandmarks.faceBox?.height].every(Number.isFinite)))
  fail('VETTED_MODEL_FACE_BOUNDING_BOX_INVALID');
 let box=null,confidence='LOW';
 if(supplied){
  const b=faceLandmarks.faceBox;
  if(b.x<0||b.y<0||b.width<10||b.height<10||
   b.x+b.width>width||b.y+b.height>height)fail('OBSERVED_FACE_OUTSIDE_IMAGE');
  box={x:b.x,y:b.y,width:b.width,height:b.height};
  confidence=faceLandmarks.provenance==='VERIFIED_LOCAL_ML_LANDMARK_MODEL'?'MODEL_REPORTED':'LOW';
 }else if(count>90&&maxX>minX&&maxY>minY){
  // Skin-colored regions are only weak silhouette cues.
  box={x:minX,y:minY,width:maxX-minX,height:maxY-minY};
 }else{
  // Cannot guess a face from a starship photo or an empty image.
  return {schema:AIG_REAL3D_V95_VISION_SCHEMA,imageSha256,width,height,
   result:'BLOCK_SOURCE_FACE_NOT_FOUND',faceBox:null,confidence:'NONE',
   candidateProportions:null,sourceHasNoVerifiedBodyObservations:true,
   identityFaceSimilarityMeasured:false,releasePASS:false};
 }
 const centerX=clamp((box.x+box.width*.5)/width,.1,.9);
 const observedFaceWidthFraction=clamp(box.width/width,.075,.65);
 const headLengthImageFraction=clamp(box.height/height,.065,.72);
 // Candidate shoulders are INFERRED from observed head proportions.
 // No hard statement that pixels confirm the shoulders.
 const shoulderHalfWidthFraction=clamp(observedFaceWidthFraction*.95,.09,.32);
 return {schema:AIG_REAL3D_V95_VISION_SCHEMA,imageSha256,width,height,
  result:'INFERRED_MODEL_CANDIDATE_ONLY',
  faceBox:box,confidence,landmarkSource:supplied?faceLandmarks.provenance??'USER_SUPPLIED':'COLOR_HEURISTIC',
  candidateProportions:{
   headCenterXNormalized:centerX,
   faceWidthImageFraction:observedFaceWidthFraction,
   headHeightImageFraction:headLengthImageFraction,
   estimatedLeftShoulderXNormalized:clamp(centerX-shoulderHalfWidthFraction,0,1),
   estimatedRightShoulderXNormalized:clamp(centerX+shoulderHalfWidthFraction,0,1),
   estimatedFullBodyHeadUnits:7.35,
   estimatedHeightMeters:1.64,
   estimatedCameraPerspective:false,
   sourceObservedBodyLengthMeters:null
  },
  sourceHasNoVerifiedBodyObservations:true,
  identityFaceSimilarityMeasured:false,
  autoGeneratedHeadAndBodyAreApproximations:true,
  trainedMLInferenceActuallyUsed:confidence==='MODEL_REPORTED',
  releasePASS:false};
}
